#!/usr/bin/env node
/**
 * Generate components/files/cwd-icon-map.ts from lib/shared/lucide-names.ts
 * — the curated name list is the single source of truth. Reads CWD_ICON_NAMES,
 * verifies every name exists in the installed lucide-react, and rewrites the
 * client map (named imports + record) so the two can never drift.
 *
 * Usage: node scripts/gen-cwd-icon-map.mjs
 */
import { readFileSync, writeFileSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";
import { createRequire } from "module";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const lucide = require("lucide-react");

const namesFile = join(root, "lib/shared/lucide-names.ts");
const src = readFileSync(namesFile, "utf8");

// Extract the string literals inside `CWD_ICON_NAMES = [...]`.
const block = src.match(/CWD_ICON_NAMES\s*=\s*\[([\s\S]*?)\]\s*as const/);
if (!block) {
  console.error("Could not find CWD_ICON_NAMES array in", namesFile);
  process.exit(1);
}
const names = [...block[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]);

const missing = names.filter((n) => !(n in lucide));
if (missing.length) {
  console.error("Missing from lucide-react:", missing.join(", "));
  process.exit(1);
}

const imports = names
  .map((n) => `  ${n},`)
  .join("\n");
const entries = names
  .map((n) => `  ${n},`)
  .join("\n");

const out =
  'import type { LucideIcon } from "lucide-react";\n' +
  "import {\n" +
  imports +
  "\n} from \"lucide-react\";\n\n" +
  "/**\n" +
  " * name → lucide component, mirroring lib/shared/lucide-names.ts.\n" +
  " * GENERATED by scripts/gen-cwd-icon-map.mjs — do not edit by hand.\n" +
  " * Re-run that script after changing lib/shared/lucide-names.ts.\n" +
  " */\n" +
  "export const CWD_ICON_MAP: Record<string, LucideIcon> = {\n" +
  entries +
  "\n};\n\nexport type { LucideIcon };\n";

writeFileSync(join(root, "components/files/cwd-icon-map.ts"), out);
console.log(`Generated cwd-icon-map.ts with ${names.length} icons.`);